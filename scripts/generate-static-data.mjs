// Bake everything the site used to read from disk at request time into src/generated/,
// because Cloudflare Workers have no filesystem. Runs before every build (npm run prebuild)
// and the output is committed so `next dev` works without it.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "src/generated");

// 1. Migrated pages and app detail pages (content/pages, content/apps) as static JSON imports.
const imports = [];
const lists = { pages: [], apps: [] };
for (const kind of ["pages", "apps"]) {
  for (const f of readdirSync(join(root, "content", kind)).filter((f) => f.endsWith(".json")).sort()) {
    const id = `${kind}_${imports.length}`;
    imports.push(`import ${id} from "${relative(out, join(root, "content", kind, f))}";`);
    lists[kind].push(id);
  }
}
writeFileSync(
  join(out, "content.ts"),
  `/* Generated by scripts/generate-static-data.mjs. Do not edit. */\n${imports.join("\n")}\n\nexport const PAGE_FILES: unknown[] = [${lists.pages.join(", ")}];\nexport const APP_FILES: unknown[] = [${lists.apps.join(", ")}];\n`,
);

// 2. Sizes of downloadable files in /public, shown next to download links.
const sizes = {};
for (const dir of ["brand", "research"]) {
  for (const f of readdirSync(join(root, "public", dir))) {
    sizes[`${dir}/${f}`] = statSync(join(root, "public", dir, f)).size;
  }
}
// 3. The published security.txt, shown verbatim on the disclosure page.
const securityTxt = readFileSync(join(root, "public/.well-known/security.txt"), "utf8").trim();

writeFileSync(
  join(out, "files.ts"),
  `/* Generated by scripts/generate-static-data.mjs. Do not edit. */\nexport const FILE_SIZES: Record<string, number> = ${JSON.stringify(sizes, null, 2)};\n\nexport const SECURITY_TXT = ${JSON.stringify(securityTxt)};\n`,
);
console.log(`generated: ${lists.pages.length} pages, ${lists.apps.length} apps, ${Object.keys(sizes).length} file sizes`);
